const seen = new Set(existing);
const extras = [];

for (const [label, value] of candidates) {
    if (seen.has(value)) continue;
    seen.add(value);
    extras.push({ label, value });
    if (extras.length === 150) break;
}

if (extras.length < 150) {
    throw new Error(`Only found ${extras.length} unique extras`);
}

const asciiCount = 70;
const kaomojiCount = 55;
const ascii = extras.slice(0, asciiCount).map((item) => `    { label: "${item.label}", value: "${item.value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}" },`);
const kaomoji = extras.slice(asciiCount, asciiCount + kaomojiCount).map((item) => `    { label: "${item.label}", value: "${item.value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}" },`);
const emoticons = extras.slice(asciiCount + kaomojiCount).map((item) => `    { label: "${item.label}", value: "${item.value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}" },`);

const content = `export const ASCII_EMOJIS_EXTRA = [
${ascii.join("\n")}
];

export const KAOMOJI_EXTRA = [
${kaomoji.join("\n")}
];

export const EMOTICONS_EXTRA = [
${emoticons.join("\n")}
];
`;

writeFileSync(new URL("../src/modules/text/_shared/asciiEmojiExtras.js", import.meta.url), content);
console.log(`Wrote ${extras.length} extras (${asciiCount} ascii, ${kaomojiCount} kaomoji, ${extras.length - asciiCount - kaomojiCount} emoticons)`);
