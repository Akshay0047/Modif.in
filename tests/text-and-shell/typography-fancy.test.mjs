import assert from "node:assert/strict";
import test from "node:test";
import { getFancyTextStyles } from "../../src/modules/text/_shared/textFormatter.js";

const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";

test("mathematical italic h uses the Letterlike Symbols exception", () => {
    const italic = getFancyTextStyles("h Hello").find(({ label }) => label === "Italic-style Unicode").value;
    assert.equal(italic, "ℎ 𝐻𝑒𝑙𝑙𝑜");
    assert.equal(italic.codePointAt(0), 0x210e);
    assert.equal(italic.includes(String.fromCodePoint(0x1d455)), false);
});

