export const ADDITIONAL_BRANDS = [];

let cachedIndex = null;

function deriveTokens(entry) {
    const tokens = new Set(entry.tokens);

    entry.domains.forEach((domain) => {
        const secondLevel = domain.split(".")[0];
        if (
            secondLevel &&
            secondLevel.length >= 5 &&
            !GENERIC_TOKEN_BLOCKLIST.has(secondLevel)
        ) {
            tokens.add(secondLevel);
        }
    });

    return [...tokens].filter((token) => token.length >= 4);
}

export function buildTrustedIndex(brands = TRUSTED_BRANDS, extraDomains = EXTRA_TRUSTED_DOMAINS) {
    const domainSet = new Set();
    const domainToBrand = new Map();
    const sldToBrands = new Map();
    const tokenToBrands = new Map();
    const allBrands = [...brands, ...ADDITIONAL_BRANDS];

    const registerDomain = (domain, entry) => {
        const normalized = normalizeDomain(domain);
        if (!normalized) return;
        domainSet.add(normalized);
        if (!domainToBrand.has(normalized)) {
            domainToBrand.set(normalized, entry);
        }

        const sld = normalized.split(".")[0];
        if (!sldToBrands.has(sld)) sldToBrands.set(sld, []);
        if (!sldToBrands.get(sld).includes(entry)) {
            sldToBrands.get(sld).push(entry);
        }
    };

    allBrands.forEach((entry) => {
        entry.domains.forEach((domain) => registerDomain(domain, entry));
        deriveTokens(entry).forEach((token) => {
            if (!tokenToBrands.has(token)) tokenToBrands.set(token, []);
            if (!tokenToBrands.get(token).includes(entry)) {
                tokenToBrands.get(token).push(entry);
            }
        });
    });

    extraDomains.forEach((domain) => {
        const normalized = normalizeDomain(domain);
        if (!normalized) return;
        domainSet.add(normalized);
        if (domainToBrand.has(normalized)) return;

        const labels = normalized.split(".").filter(Boolean);
        let parentBrand = null;
        for (let offset = 1; offset < labels.length; offset += 1) {
            const parent = labels.slice(offset).join(".");
            if (domainToBrand.has(parent)) {
                parentBrand = domainToBrand.get(parent);
                break;
            }
        }

        domainToBrand.set(
            normalized,
            parentBrand ?? {
                name: normalized,
                category: "extra",
                domains: [normalized],
                tokens: [],
                trustSubdomains: true,
            },
        );
    });

    return {
        brands: allBrands,
        domainSet,
        domainToBrand,
        sldToBrands,
        tokenToBrands,
        brandCount: allBrands.length,
        domainCount: domainSet.size,
        tokenCount: tokenToBrands.size,
    };
}

export function getTrustedIndex() {
    if (!cachedIndex) {
        cachedIndex = buildTrustedIndex();
    }
    return cachedIndex;
}

export function invalidateTrustedIndex() {
    cachedIndex = null;
}

export function addTrustedBrands(entries) {
    const list = Array.isArray(entries) ? entries : [entries];
    ADDITIONAL_BRANDS.push(...list);
    invalidateTrustedIndex();
    return getTrustedIndex();
}

export function addTrustedDomains(domains) {
    const list = Array.isArray(domains) ? domains : [domains];
    EXTRA_TRUSTED_DOMAINS.push(...list.map(normalizeDomain));
    invalidateTrustedIndex();
    return getTrustedIndex();
}

export function getTrustedStats() {
    const index = getTrustedIndex();
    return {
        brandCount: index.brandCount,
        domainCount: index.domainCount,
        tokenCount: index.tokenCount,
    };
}
