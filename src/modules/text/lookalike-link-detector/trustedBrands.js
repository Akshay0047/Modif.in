/**
 * Trusted brand / domain registry for the Lookalike Link Detector.
 *
 * HOW TO ADD ENTRIES LATER
 * ------------------------
 * 1. Append a `brand()` object to the matching category array below, or to
 *    `ADDITIONAL_BRANDS` if you do not want to pick a category yet.
 * 2. List official hostnames only (no scheme, no `www.`). Include every
 *    legitimate TLD the brand actually operates.
 * 3. Add `tokens` for extra impersonation names (`gmail`, `office365`,
 *    `icloud`) when those strings are not already a listed second-level domain.
 * 4. Set `trustSubdomains: false` for public hosting platforms where user
 *    sites live on subdomains (`github.io`, `blogspot.com`, …).
 * 5. For one-off domains without a full brand record, push them onto
 *    `EXTRA_TRUSTED_DOMAINS`.
 *
 * `addTrustedBrands()` / `addTrustedDomains()` can also register entries at
 * runtime; the lookup index rebuilds on the next analysis.
 */

function unique(values) {
    return [...new Set(values.map((value) => normalizeDomain(value)).filter(Boolean))];
}

export function normalizeDomain(value) {
    return String(value)
        .trim()
        .toLowerCase()
        .replace(/^www\./, "")
        .replace(/\.$/, "");
}

export function brand(name, category, domains, options = {}) {
    return {
        name,
        category,
        domains: unique(domains),
        tokens: unique(options.tokens ?? []),
        trustSubdomains: options.trustSubdomains !== false,
    };
}

export function tlds(secondLevel, suffixList) {
    return suffixList.map((suffix) => `${secondLevel}.${suffix}`);
}

