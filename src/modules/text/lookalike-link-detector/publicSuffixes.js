const SUFFIX_SET = new Set(
    MULTI_PART_PUBLIC_SUFFIXES.map((suffix) => suffix.toLowerCase()),
);

export function getRegistrableDomain(hostname) {
    const labels = String(hostname)
        .toLowerCase()
        .replace(/\.$/, "")
        .split(".")
        .filter(Boolean);

    if (labels.length <= 1) {
        return labels.join(".");
    }

    for (let index = 0; index < labels.length - 1; index += 1) {
        const suffix = labels.slice(index).join(".");
        if (SUFFIX_SET.has(suffix)) {
            const start = index - 1;
            if (start < 0) return suffix;
            return labels.slice(start).join(".");
        }
    }

    return labels.slice(-2).join(".");
}

export function getSecondLevelLabel(hostname) {
    const registrable = getRegistrableDomain(hostname);
    if (!registrable) return "";

    const labels = registrable.split(".");
    for (let index = 1; index < labels.length; index += 1) {
        const suffix = labels.slice(index).join(".");
        if (SUFFIX_SET.has(suffix)) {
            return labels[index - 1] ?? "";
        }
    }

    return labels[0] ?? "";
}
